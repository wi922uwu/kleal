// ------------------------------------------------- 10. огибающая: арифметика столбиков
//
// Считает не глаз, а код: обе функции гоняются по-настоящему, а не сверяются регуляркой.
console.log('\nстолбики голосового считаются, а не выдумываются');
{
  const src = code('src/voice.tsx');
  // Берём тело функции из ИСХОДНИКА и выполняем его: проверять регуляркой по тексту — значит
  // проверять формулировку, а не то, что посчитается. Аннотации типов снимаются, потому что
  // Node их не понимает; на арифметику они не влияют.
  const strip = (name) => {
    const from = src.indexOf(`export const ${name} =`);
    const to = src.indexOf('\n};', from);
    check(`${name} нашёлся в исходнике`, from >= 0 && to > from, 'переименовали?');
    return src.slice(from, to + 3)
      .replace(`export const ${name} =`, `const ${name} =`)
      // Массивы первыми: иначе `: number` съедается раньше, а `[]` остаётся висеть.
      .replace(/: (?:number\[\]|string\[\]|number|string)/g, '');
  };
  const run = new Function(
    `const WAVE_BARS = 34;\n${strip('barsFrom')}\n${strip('pseudoPeaks')}\nreturn { barsFrom, pseudoPeaks };`
  )();

  const quiet = run.barsFrom([0.02, 0.03, 0.01, 0.04], 4);
  check('тихая запись всё равно видна',
    quiet.length === 4 && Math.max(...quiet) === 1,
    'без нормировки сказанное вполголоса — ровная ниточка');
  check('столбики не выходят за пределы',
    run.barsFrom([0.1, 0.9, 0.5, 0.2, 0.7], 34).every((v) => v >= 0.1 && v <= 1));
  check('пустая запись не роняет расчёт', run.barsFrom([], 34).length === 0);
  check('число столбиков не зависит от длины записи',
    run.barsFrom(Array.from({ length: 7 }, (_, i) => i / 7), 34).length === 34 &&
    run.barsFrom(Array.from({ length: 900 }, (_, i) => (i % 10) / 10), 34).length === 34,
    'иначе минутное сообщение и секундное выглядят по-разному по плотности');

  const a = run.pseudoPeaks('voice-1');
  check('одно и то же сообщение всегда одной формы',
    JSON.stringify(a) === JSON.stringify(run.pseudoPeaks('voice-1')),
    'форма, меняющаяся между кадрами, читается как помеха');
  check('разные сообщения — разной формы',
    JSON.stringify(a) !== JSON.stringify(run.pseudoPeaks('voice-2')));
  check('выдуманная форма тоже в пределах',
    a.length === 34 && a.every((v) => v >= 0.14 && v <= 1));
}

