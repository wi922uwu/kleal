// ------------------------------------------------- 15. системная строка группы — код, а не фраза
//
// Сервер писал событие английским предложением, клиент узнавал его регуляркой. Из двадцати семи
// событий узнавались пять, и промах был НЕ ВИДЕН: «X left. Y is now the organiser» не подходит под
// шаблон «X left the group» и приезжал на русский экран по-английски. Хуже того, любая правка
// формулировки на сервере тихо ломала разбор — ни ошибки, ни следа.
console.log('\nсистемная строка группы приходит кодом');
{
  const py = fs.readFileSync(path.join(ROOT, '..', 'kleal-ms/services/matching/app.py'), 'utf8');
  const gr = code('src/groups.ts');

  check('помощник кладёт код рядом с текстом',
    /def _gi_say\(g, text, kind="system", code=None, \*\*fields\)/.test(py) && /row\["sys"\]/.test(py),
    'без этого клиенту нечего читать, кроме английской фразы');

  // Каждый вызов обязан назвать событие. Новый вызов без кода — это молча непереведённая строка.
  // Само объявление функции тоже содержит «_gi_say(g,» — оно не вызов, и в счёт не идёт.
  const calls = py.split('_gi_say(g,').slice(1).filter((c) => !c.startsWith(' text, kind='));
  const noCode = calls.filter((c) => !/code="/.test(c.slice(0, 400)));
  check('каждое событие ленты названо кодом', noCode.length === 0,
    'без кода осталось вызовов: ' + noCode.length);

  // Коды сервера и разбор клиента обязаны совпадать поимённо — иначе строка снова уедет сырой.
  const serverCodes = [...new Set([...py.matchAll(/code="([a-z_]+)"/g)].map((m) => m[1]))].sort();
  const clientCodes = [...new Set([...gr.matchAll(/c === '([a-z_]+)'/g)].map((m) => m[1]))].sort();
  const missing = serverCodes.filter((c) => !clientCodes.includes(c));
  check('клиент знает каждый код сервера', missing.length === 0,
    'сервер шлёт, клиент не понимает: ' + missing.join(', '));
  check('кодов не меньше двух десятков', serverCodes.length >= 20,
    'нашлось: ' + serverCodes.length);

  // Старый разбор оставлен НАРОЧНО: в ленте лежат сообщения, записанные до появления кодов.
  check('разбор английского оставлен запасным путём',
    /joined the group/.test(gr) && /groupSysLine\(text: string, sys\?: GroupSys\)/.test(gr),
    'выкинуть его — значит потерять историю старых групп');

  check('экран передаёт код в отрисовку',
    /groupSysLine\(String\(m\.text \|\| ''\), \(m as any\)\.sys\)/.test(code('app/group.tsx')),
    'иначе сервер шлёт код, а клиент его не видит');
}

