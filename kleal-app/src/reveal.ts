/**
 * РОВНОЕ ПОЯВЛЕНИЕ ТЕКСТА.
 *
 * Буквы приезжают по сети РЫВКАМИ: измерено — 201 кусок на 656 символов, и между кусками то
 * 10 мс, то 400. Если рисовать их как пришли, текст дёргается: строка стоит, потом прыгает на
 * полфразы. Ощущение не «печатает», а «подтормаживает».
 *
 * Поэтому приход и показ развязаны. Пришедшее копится в буфере, а на экран выдаётся РОВНЫМ
 * темпом — как печатают все большие модели, и по той же причине: сеть неровная, а чтение должно
 * быть ровным.
 *
 * ТЕМП ДОГОНЯЮЩИЙ, а не постоянный. Постоянный либо отстаёт (модель дописала, а экран ещё
 * ползёт), либо обгоняет (буфер пуст, курсор стоит). Скорость считается от остатка: чем больше
 * накопилось, тем быстрее выдаём, а на закрытом потоке дописываем без остатка.
 *
 * ГРАНИЦА ПОКАЗА НЕ РЕЖЕТ РАЗМЕТКУ. Показать «**Лон» значит показать звёздочки: разметка ещё не
 * закрыта, и человек видит мусор, который через миг превратится в жирный текст. Поэтому хвост
 * с незакрытым маркером придерживается — ровно как в потоке придерживается начало конверта.
 */

/** Сколько символов в секунду при пустом буфере. Ниже — «залипает», выше — мельтешит. */
const BASE_CPS = 120;
/** Догон: сколько буфера съедаем за секунду сверх базового темпа. */
const CATCHUP = 2.2;
/** Шаг таймера. 16 мс — это кадр; чаще смысла нет, реже видно ступеньки. */
const TICK_MS = 16;

/** Обрезать хвост, если в нём открыт маркер разметки. */
export function safeCut(text: string): string {
  let t = text;
  // Незакрытый жирный/курсив/код: возвращаемся к позиции перед последним маркером.
  for (const mark of ['**', '`']) {
    const n = t.split(mark).length - 1;
    if (n % 2 === 1) t = t.slice(0, t.lastIndexOf(mark));
  }
  // Строка, начатая решёткой или маркером списка, но ещё без текста — пустой заголовок мигает.
  t = t.replace(/\n\s*(#{1,6}|[-*•]|\d+[.)])\s*$/, '\n');
  // Начатая строка таблицы без ЗАКРЫВАЮЩЕЙ палки — она бы отрисовалась обычным абзацем, а
  // через миг стала строкой таблицы: столбцы прыгали бы на каждом кадре. Проверять надо конец
  // строки, а не отсутствие палок внутри: в «| Цена | Ре» их уже две.
  t = t.replace(/\n[ \t]*\|[^\n]*$/, (m) => (m.trimEnd().endsWith('|') ? m : '\n'));
  return t;
}

export type Reveal = {
  /** Пришёл кусок от сети. */
  push: (delta: string) => void;
  /** Поток закончился: дописать остаток и остановиться. */
  finish: () => void;
  /** Бросить всё (человек ушёл с экрана). */
  stop: () => void;
};

/**
 * Создать «печатающую машинку».
 *
 * `onShow` зовётся с тем, что должно быть НА ЭКРАНЕ прямо сейчас, — целиком, а не приращением:
 * экран хранит одну строку, и склеивать её из кусков значило бы держать вторую копию.
 */
export function makeReveal(onShow: (shown: string) => void): Reveal {
  let target = '';
  let shownLen = 0;
  let done = false;
  let timer: ReturnType<typeof setInterval> | null = null;
  let last = Date.now();

  const paint = () => onShow(safeCut(target.slice(0, shownLen)));

  const tick = () => {
    const now = Date.now();
    const dt = Math.max(0, now - last) / 1000;
    last = now;
    const left = target.length - shownLen;
    if (left <= 0) {
      if (done) stop();
      return;
    }
    // Догон: базовый темп плюс доля остатка. На закрытом потоке добавляем ещё, чтобы конец
    // не тянулся, — человек уже дочитал до этого места.
    const cps = BASE_CPS + left * CATCHUP + (done ? left * 3 : 0);
    shownLen = Math.min(target.length, shownLen + Math.max(1, Math.round(cps * dt)));
    paint();
    if (done && shownLen >= target.length) stop();
  };

  const start = () => {
    if (timer) return;
    last = Date.now();
    timer = setInterval(tick, TICK_MS);
  };

  function stop() {
    if (timer) clearInterval(timer);
    timer = null;
  }

  return {
    push: (delta: string) => {
      target += delta;
      start();
    },
    finish: () => {
      done = true;
      // Поток мог закончиться раньше первого тика — тогда таймера нет, и без запуска текст
      // так и не появился бы вовсе.
      start();
    },
    stop: () => {
      stop();
      // Показываем всё, что успело прийти: обрывать на полуслове хуже, чем показать целиком.
      shownLen = target.length;
      paint();
    },
  };
}
