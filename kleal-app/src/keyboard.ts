/**
 * Сколько места снизу занимает клавиатура ПРЯМО СЕЙЧАС — и надо ли поднимать на это поле ввода.
 *
 * Зачем это вообще. Во всех экранах с полем внизу стоит
 *
 *     <KeyboardAvoidingView behavior={Platform.OS === 'ios' ? 'padding' : undefined}>
 *
 * — то есть на Android компонент не делает НИЧЕГО. Это проверено на исходниках: между RN 0.81.5 и
 * 0.86.3 файл KeyboardAvoidingView.js отличается двумя строками, и `behavior === undefined`
 * по-прежнему попадает в `default:`, где рендерится голый <View> без всякого подъёма. Переход на
 * SDK 57 здесь ничего не изменил, и надежда «теперь платформа сама» — ложная.
 *
 * Настоящее решение — react-native-keyboard-controller, но это нативный модуль, а с ним кончается
 * Expo Go (см. AGENTS.md). Поэтому поднимаем сами, из JS.
 *
 * ───────────────────────────────────────────────────────────────────────────────────────────────
 * ЧТО БЫЛО СЛОМАНО ДО 7 СЕНТЯБРЯ 2026 И ПОЧЕМУ «ТОЛЬКО НА НЕКОТОРЫХ»
 *
 * Считалось так:
 *     already = screen.height - window.height      // «насколько окно короче экрана»
 *     covered = screen.height - keyboardTopY       // всё, что ниже верхнего края клавиатуры
 *     inset   = covered - already
 *
 * `already` — это сумма ВСЕХ декораций, которых нет в метриках окна: строки состояния СВЕРХУ,
 * панели навигации снизу, выреза. А `covered` меряется только снизу. Из нижней величины вычиталась
 * верхняя, и подъём недобирал ровно высоту строки состояния — 24 точки, а с вырезом до 48.
 *
 * Почему это не видно на телефоне, где замеряли: там было window == screen (замер kbH=244,
 * screenY=540, window=screen=832), `already` вышел нулём, и ошибка обнулилась вместе с ним.
 * А равны они не везде. В Expo Go окно уходит edge-to-edge на любой версии Android, но ВНУТРЕННИЙ
 * флаг RN, от которого зависит `Dimensions.get('window')`, ставится только на Android 15+. На
 * Android 14 и ниже window остаётся «экран минус панели», `already` равен 70–100 точкам, и поле
 * встаёт под клавиатурой ровно на эту величину. Вот и «на некоторых».
 *
 * Вторая беда той же формулы — она считала ОДИН РАЗ, в момент события, и запоминала число.
 * Поворот экрана, разделённый экран, раскрытая раскладушка меняют геометрию, а запомненное число
 * остаётся прежним.
 *
 * ───────────────────────────────────────────────────────────────────────────────────────────────
 * КАК СЧИТАЕТСЯ ТЕПЕРЬ
 *
 *     inset = max(0, (frame.y + frame.height) - keyboardTopY)
 *
 * То есть: где кончается наша область — минус где начинается клавиатура. Обе величины в одной
 * системе координат, экранной, и обе про низ. Ровно это выражение стоит внутри самого
 * KeyboardAvoidingView в RN (`_relativeKeyboardHeight`) — берём проверенную временем формулу, а не
 * сочиняем свою.
 *
 * Она верна во всех четырёх случаях сразу:
 *   • окно во весь экран (edge-to-edge)          → поднимаем на всё закрытое;
 *   • окно короче на строку состояния            → верхняя декорация в расчёт не входит вовсе;
 *   • окно короче на строку состояния и панель   → то же самое;
 *   • систёма сама ужала окно под клавиатуру      → низ области уже выше клавиатуры, разность 0.
 *
 * Последний случай важен отдельно: на Android 10 и ниже `adjustResize` отключить нечем, и система
 * поднимает поле сама. Прежняя формула про это знала через `already` и ошибалась; эта знает через
 * саму геометрию и выключается сама, без единой проверки версии.
 *
 * ХРАНИМ КРАЙ, А НЕ ВЫСОТУ. В состоянии лежит экранная координата верха клавиатуры, а разность
 * считается ПРИ ОТРИСОВКЕ, с текущим кадром. Поэтому поворот, разделённый экран и раскладушка
 * пересчитываются сами: изменился кадр — изменился и отступ, без единого события от клавиатуры.
 */
import { useEffect, useState } from 'react';
import { Dimensions, Keyboard, Platform } from 'react-native';
import { useSafeAreaFrame } from 'react-native-safe-area-context';

export function useKeyboardInset(): number {
  /** Экранная координата ВЕРХНЕГО края клавиатуры. 0 — клавиатуры нет. */
  const [kbTop, setKbTop] = useState(0);
  const frame = useSafeAreaFrame();

  useEffect(() => {
    if (Platform.OS !== 'android') return;

    const show = (e: any) => {
      const top = Math.round(Number(e?.endCoordinates?.screenY || 0));
      if (top > 0) { setKbTop(top); return; }
      /*
        Запасной путь: на части устройств (сэндбоксинг координат у производителя, плавающая
        клавиатура) `screenY` приходит нулём. Тогда восстанавливаем край из высоты. Это хуже —
        собственная высота клавиатуры не знает про панель навигации под ней, — но лучше, чем
        не поднять вовсе.
      */
      const h = Math.round(Number(e?.endCoordinates?.height || 0));
      setKbTop(h > 0 ? Math.max(0, Dimensions.get('screen').height - h) : 0);
    };

    const subs = [
      Keyboard.addListener('keyboardDidShow', show),
      /*
        `keyboardDidChangeFrame` — не роскошь. Смена раскладки, панель эмодзи и строка подсказок
        меняют высоту БЕЗ повторного `keyboardDidShow`: клавиатура не закрывалась, значит и не
        открывалась. Без этой подписки поле оставалось поднятым на старую высоту.
      */
      Keyboard.addListener('keyboardDidChangeFrame', show),
      Keyboard.addListener('keyboardDidHide', () => setKbTop(0)),
    ];
    return () => { subs.forEach((s) => s.remove()); };
  }, []);

  if (Platform.OS !== 'android' || !kbTop) return 0;
  const bottom = Number(frame?.y || 0) + Number(frame?.height || 0);
  if (!bottom) return 0;                      // кадра ещё нет — не поднимаем наугад
  return Math.max(0, Math.round(bottom - kbTop));
}


/**
 * Отступ снизу для панели с полем ввода: пока клавиатуры нет — безопасная зона (жест-бар),
 * когда она открыта — всё, что она закрыла. Складывать их нельзя: клавиатура и так закрывает
 * жест-бар.
 *
 * ЗАЗОР НАД КЛАВИАТУРОЙ. Ровный подъём ставит поле впритык к её верхнему краю — две светлые
 * плашки без единой границы читаются как одна, и непонятно, где кончается ввод и начинаются
 * клавиши. Сообщено с телефона со ссылкой на Telegram, где такой зазор есть. Он равен той же
 * величине, что и покой без клавиатуры (`min`): поле дышит одинаково в обоих состояниях.
 */
export function dockBottom(safeBottom: number, keyboard: number, min = 10): number {
  return keyboard > 0 ? keyboard + min : Math.max(safeBottom, min);
}


/**
 * Замер для отладки на чужом телефоне.
 *
 * Клавиатура ломается на устройствах, которых у нас нет, и «попробуй ещё раз» тут не работает:
 * различия в том, как производитель считает координаты, по описанию не восстановить. Эта функция
 * отдаёт все числа, по которым видно, какой из четырёх случаев на телефоне и сходится ли формула.
 * Показать её можно откуда угодно — например временно вывести строкой на экране ввода.
 */
export function keyboardDebug(kbTop: number, frame: { y: number; height: number }): string {
  const scr = Dimensions.get('screen');
  const win = Dimensions.get('window');
  const bottom = Math.round(frame.y + frame.height);
  return [
    `api=${Platform.Version}`,
    `screen=${Math.round(scr.height)}`,
    `window=${Math.round(win.height)}`,
    `frame=${Math.round(frame.y)}+${Math.round(frame.height)}=${bottom}`,
    `kbTop=${kbTop}`,
    `inset=${Math.max(0, bottom - kbTop)}`,
  ].join(' ');
}
