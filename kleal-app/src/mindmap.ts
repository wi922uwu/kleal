/**
 * Карта интересов: восемь материнских категорий и сорок четыре занятия вокруг них.
 *
 * ЧТО ЭТО ЗА ЭКРАН. Первый заход на шаге увлечений: поле пузырей, где крупный — категория, а
 * мелкие вокруг — занятия из неё. Палец не двигает карту, а приближает то, что под ним, как лупа;
 * иначе подпись в пятнадцать пикселей не прочитать. Тап выбирает. Разговор с агентом идёт ПОСЛЕ —
 * карта даёт широкий быстрый выбор, агент уточняет и добирает своё.
 *
 * ДАННЫЕ НЕ ЗАВОДЯТСЯ ЗАНОВО. Категории — восемь корней WHEEL_TREE, занятия — колода DECK():
 * у обоих уже есть канонический английский ключ и подписи на двух языках. Второй каталог
 * разошёлся бы с первым на первой же правке.
 *
 * СВЯЗЬ «ЗАНЯТИЕ → КАТЕГОРИЯ» СОБИРАЕТСЯ ИЗ ДЕРЕВА, но не целиком: из сорока четырёх ключей
 * колоды двадцать семь есть в WHEEL_TREE, семнадцати там нет вовсе (run, photo, museums…).
 * Для них — явная таблица ниже, и это честнее, чем делать вид, что дерево знает всё. Сторож
 * `orphans()` возвращает карточки без категории, кроме снятых намеренно (`OFF_TAXONOMY`): новая
 * карта, добавленная в колоду, не имеет права молча провалиться в угол экрана. Смоука на нём,
 * вопреки прежней редакции этого комментария, НЕТ — проверка ниже в tools/interest_keys_test.js.
 */
import { DECK, type DeckTone } from './interests-deck';
import { WHEEL_TREE, nodeLabel, type WheelNode } from './interests-wheel';

export type Bubble = {
  key: string;
  label: string;
  /** Ключ материнской категории; у самой категории — собственный ключ. */
  root: string;
  kind: 'root' | 'leaf';
  /** Центр в долях поля: 0..1 по каждой оси. В пиксели переводит компонент. */
  x: number;
  y: number;
  /** Диаметр в пикселях при обычном (не приближённом) состоянии. */
  size: number;
};

/** Восемь корней дерева — они же материнские пузыри. */
export const ROOTS = (): WheelNode[] => WHEEL_TREE;

/**
 * ТОН КАТЕГОРИИ — ОДИН К ОДНОМУ, ВОСЕМЬ НА ВОСЕМЬ.
 *
 * Раньше цвет на карте не значил ничего: категории были маджентовые, занятия красные. Оба решения
 * оказались ошибками, и обе видно только рядом с остальным приложением.
 *
 * Красный — цвет ДЕЙСТВИЯ И ВЫБРАННОГО, это записано прямо в токенах (src/theme.ts, комментарий
 * к `deckTone`): им залиты главные кнопки, выбранные чипы, плашка ошибки. Им же были залиты сорок
 * четыре НЕвыбранных пузыря, а в двенадцати пикселях под полем стояли чипы выбранного и главная
 * кнопка того же цвета — экран сообщал, что выбрано всё.
 *
 * Маджента же вообще не цвет темы: `brandMagenta` заведён как второй конец градиента логотипа.
 * Пара с красным давала контраст 1.17 — в оттенках серого они неразличимы, то есть иерархии не
 * было, её изображал только размер.
 *
 * Восемь тонов по три цвета на каждый в теме уже лежат, и категорий ровно восемь. Теперь цвет
 * говорит «это одна тема», куст читается кустом без единого жеста, а красный свободен и означает
 * ровно то, что означает везде.
 */
export const ROOT_TONE: Record<string, DeckTone> = {
  sports: 'lime',
  social: 'amber',
  culture: 'slate',
  outdoors: 'teal',
  music: 'rose',
  games: 'indigo',
  learning: 'sand',
  tech: 'violet',
};

/**
 * Ключи, которых в WHEEL_TREE нет. Не «костыль», а признание факта: колода и дерево росли
 * отдельно, и сводить их одним движением значит переписать курируемое дерево ради раскладки.
 * Таблица маленькая и проверяемая; если она разойдётся с колодой, это увидит `orphans()`.
 */
const EXTRA_ROOT: Record<string, string> = {
  breakfast: 'social',
  dancing: 'music',
  'food market': 'social',
  languages: 'learning',
  quiz: 'games',
  run: 'sports',
};

/*
 * СПИСОК ПОХУДЕЛ ПОСЛЕ ПЕРЕИМЕНОВАНИЯ, и это не уборка, а починка. Приведя ключи колоды к канону
 * (`museums` -> `museum`, `photo` -> `photography`, `citywalks` -> `walk`), я обнаружил, что семь
 * из них УЖЕ ЕСТЬ В ДЕРЕВЕ: concert, course, dogwalk, exhibition, museum, photography, walk.
 * Оставь их здесь — и карта поставила бы каждый дважды, листом дерева и карточкой колоды, с
 * одинаковым ключом: два пузыря на один интерес, конфликт ключей в списке и выбор, снимающий сам
 * себя. Поймано сторожем tools/interest_keys_test.js, для того он и написан.
 *
 * Здесь остаётся только то, чего в дереве нет.
 */

/*
 * ЧЕТЫРЕ КАРТОЧКИ СНЯТЫ С ПОЛЯ: «Бильярд», «Боулинг», «Подкасты» и «Море».
 *
 * Не по вкусу, а потому что их некуда записать. Онбординг с 27.08 проверяет каждый интерес по
 * общей таксономии (`interest_normalization.trusted_interest`, каталог собирается из TAXONOMY
 * сервиса подбора и matching_core/taxonomy/canonical_taxonomy.json) и отклоняет ВЕСЬ вызов
 * `register`, если хоть один ключ неизвестен: `{"ok": false, "error": "unconfirmed interests: …"}`.
 * У этих четырёх узла нет ни одного — проверено запросом к живому нормализатору. Человек, выбравший
 * «Боулинг», упирался бы в «Профиль не сохранился» и не мог закончить анкету вообще.
 *
 * Остальные восемь из этого списка были той же бедой, но по другой причине — расхождение в
 * написании, множественное против единственного: `museums`/`museum`, `photo`/`photography`,
 * `citywalks`/`walk`. Они переименованы в колоде под канон, и теперь проходят.
 *
 * Вернуть эти четыре можно ровно одним способом: завести им узлы в общей таксономии. Это чужая
 * territory — сервис подбора, — поэтому здесь только снято и записано, почему.
 */

/** Ключ корня для узла дерева: спуск с запоминанием, откуда пришли. */
function rootFromTree(key: string): string | null {
  const walk = (nodes: WheelNode[], root: string): string | null => {
    for (const n of nodes) {
      if (n.key === key) return root;
      if (n.kids?.length) {
        const hit = walk(n.kids, root);
        if (hit) return hit;
      }
    }
    return null;
  };
  for (const top of WHEEL_TREE) {
    if (top.key === key) return top.key;
    const hit = walk(top.kids || [], top.key);
    if (hit) return hit;
  }
  return null;
}

/** Категория занятия: сперва дерево, потом таблица. Пусто — значит карточка осиротела. */
export function rootOf(key: string): string | null {
  return rootFromTree(key) || EXTRA_ROOT[key] || null;
}

/**
 * Карточки, снятые с поля ОСОЗНАННО, — у них нет узла в общей таксономии. Разбор в комментарии
 * к `EXTRA_ROOT`. Список существует ради `orphans()`: без него «снято намеренно» и «забыли
 * подключить новую карточку» выглядели бы одинаково, и сторож перестал бы что-либо значить.
 */
export const OFF_TAXONOMY = ['sea', 'podcasts', 'billiards', 'bowling'];

/**
 * Карточки колоды, которым не нашлось категории И которые не сняты намеренно. Пусто — здоровое
 * состояние: новая карта, добавленная в колоду, не имеет права молча провалиться в угол экрана.
 */
export function orphans(): string[] {
  return DECK().map((c) => c.key)
    .filter((k) => !rootOf(k) && !OFF_TAXONOMY.includes(k));
}

// ---------------------------------------------------------------- раскладка
//
// ПОЧЕМУ СЧИТАЕТСЯ, А НЕ ЗАБИТО РУКАМИ. Пятьдесят две пары координат, выписанные в файл, живут
// ровно до первой новой карточки: она встанет поверх соседа, и поправить придётся всё поле.
// Здесь позиции выводятся из состава — добавили карту, поле само раздвинулось.
//
// ПОЧЕМУ БЕЗ СЛУЧАЙНОСТИ. Раскладка обязана быть одинаковой при каждом открытии: человек,
// вернувшийся на шаг назад, ищет пузырь глазами там, где видел его в прошлый раз. Поэтому ни
// Math.random, ни времени — только состав и порядок.

const GOLDEN = 2.39996;          // золотой угол: даёт равномерный веер без видимых рядов

/*
 * РАЗМЕРЫ ПРИ ОПОРНОМ ПОЛЕ 350x500 — дальше они множатся на масштаб поля (см. `buildMap`).
 *
 * Разброс расширен намеренно. Было 66 против 26–40, то есть категория крупнее спутника всего
 * в 1.65–2.5 раза; на борде тот же разброс 4.7 (71 против 15). Чем ближе размеры, тем сильнее
 * работу иерархии приходилось перекладывать на цвет — а цвет её как раз и не давал.
 */
/*
  РАЗМЕРЫ ПЕРЕСМОТРЕНЫ ПОД ПАЛЕЦ И ПОД ТЕЛЕФОН.

  Спутник в девять пикселей — это не маленький кружок, это точка: в неё нельзя прицелиться, её
  нельзя прочитать даже под лупой, и держать таких полтораста дороже, чем телефон тянет (у каждого
  свой вид, свой сдвиг и свой масштаб на каждом кадре). Поле выглядело густым, но работать с ним
  было нечем — отсюда и «багованая», и «лагает» разом.

  Теперь спутник начинается с четырнадцати и доходит до двадцати шести: под лупой это уже кружок,
  в который целятся, а не угадывают. Категория выросла соразмерно, чтобы иерархия осталась видна.
*/
const ROOT_SIZE = 54;
const LEAF_MIN = 14;
const LEAF_MAX = 26;

/**
 * СКОЛЬКО ЗАНЯТИЙ НА ПОЛЕ.
 *
 * Раньше их было сорок четыре — вся колода. Колода на это и не рассчитана: она набор карточек для
 * свайпа, где сорока штук хватает, чтобы человек не устал. Поле — другое: по нему водят пальцем и
 * ищут СВОЁ, и чем гуще выбор, тем выше шанс, что своё там есть.
 *
 * Источник теперь дерево таксономии, а не колода: в нём двести шестьдесят шесть листьев, у каждого
 * есть канонический английский ключ и подписи на двух языках, и матчинг ранжирует ровно по этим
 * ключам. Берём из каждой категории её долю, пропорционально размеру, — иначе «Учёба» с двадцатью
 * четырьмя листьями отдала бы всё, а «Культура» с сорока одним осталась бы урезанной.
 */
/*
  ЧИСЛО СНИЖЕНО СО СТА ПЯТИДЕСЯТИ. Полтораста было выбрано под мысль «чем гуще выбор, тем выше шанс
  найти своё», и мысль верная — но она молча предполагала, что все полтораста можно РАЗГЛЯДЕТЬ. При
  девяти пикселях на штуку нельзя: половина поля уходила под перекрытия, лупа вытаскивала соседа
  вместо нужного, а телефон считал триста видов на каждое движение пальца.

  Девяносто крупных читаются и нажимаются, а густота поля на глаз та же: площадь под кружками даже
  выросла. Всё, что не поместилось, никуда не делось — оно набирается разговором, и это основной
  путь, а карта всегда была быстрым.
*/
/*
  ЧИСЛО ВЕРНУЛОСЬ ВВЕРХ, ПОТОМУ ЧТО ПОМЕНЯЛСЯ ЭКРАН. Девяносто было потолком плотности: все занятия
  лежали разом, и каждое лишнее делало цели мельче пальца. Теперь куст открывают, и всё поле
  достаётся ему одному — двум десяткам занятий там просторно, а радиус компонент считает от их
  числа сам. Значит ограничивать широту больше нечем, и она возвращается к тому, ради чего
  бралась: чем гуще выбор, тем выше шанс, что своё там есть.
*/
const LEAF_CAP = 176;

/**
 * Центры категорий — по спирали Фибоначчи от середины поля. Спираль выбрана не ради красоты:
 * она раскладывает восемь точек без сгущений и без пустот, чего не даёт ни сетка (видны ряды),
 * ни кольцо (середина пустая).
 */
function rootCenters(n: number): Array<{ x: number; y: number }> {
  const out: Array<{ x: number; y: number }> = [];
  for (let i = 0; i < n; i++) {
    const t = (i + 0.5) / n;
    const r = 0.5 * Math.sqrt(t);          // sqrt — иначе центр забит, а края пусты
    const a = i * GOLDEN;
    out.push({ x: 0.5 + r * Math.cos(a) * 0.92, y: 0.5 + r * Math.sin(a) * 0.92 });
  }
  return out;
}

/** Полная карта: категории плюс их занятия, с координатами в долях поля. */
/** Лист дерева — узел без потомков. Именно они настоящие занятия, остальные узлы — разделы. */
function treeLeaves(node: WheelNode, out: Array<{ key: string; label: string }>): void {
  // ПОДПИСЬ ЧЕРЕЗ nodeLabel, А НЕ node.ru. Здесь стояло `node.ru`, и карта показывала полторы
  // сотни русских пузырей человеку с английским интерфейсом — а английский язык по умолчанию,
  // то есть это видел каждый не-русский на пятом шаге регистрации. Переводчик лежал рядом,
  // в interests-wheel, и просто не был вызван.
  if (!node.kids?.length) { out.push({ key: node.key, label: nodeLabel(node) }); return; }
  for (const kid of node.kids) treeLeaves(kid, out);
}

/**
 * Занятия по категориям: доля от `LEAF_CAP`, пропорциональная числу листьев в разделе.
 *
 * Порядок внутри раздела НЕ трогаем и берём первые: дерево курировано, и в начале каждого раздела
 * стоит то, чем занимаются чаще. Сортировка по алфавиту или тасовка потеряли бы эту работу.
 *
 * Карточки колоды, которых в дереве нет (`EXTRA_ROOT`, семнадцать штук вроде «Бега» и «Караоке»),
 * дописываются сверх доли: они попали в колоду именно потому, что их спрашивают, и терять их ради
 * ровного счёта неправильно.
 */
function leavesByRoot(): Map<string, Array<{ key: string; label: string }>> {
  const roots = ROOTS();
  const all = new Map<string, Array<{ key: string; label: string }>>();
  let total = 0;
  for (const r of roots) {
    const acc: Array<{ key: string; label: string }> = [];
    treeLeaves(r, acc);
    all.set(r.key, acc);
    total += acc.length;
  }
  const extra = new Map<string, Array<{ key: string; label: string }>>();
  for (const c of DECK()) {
    if (!(c.key in EXTRA_ROOT)) continue;
    const r = EXTRA_ROOT[c.key];
    extra.set(r, [...(extra.get(r) || []), { key: c.key, label: c.label }]);
  }
  const out = new Map<string, Array<{ key: string; label: string }>>();
  for (const r of roots) {
    const own = all.get(r.key) || [];
    const add = extra.get(r.key) || [];
    const share = Math.max(1, Math.round((LEAF_CAP * own.length) / total) - add.length);
    out.set(r.key, [...own.slice(0, share), ...add]);
  }
  return out;
}

export function buildMap(fieldW = 350, fieldH = 500): Bubble[] {
  /*
    МАСШТАБ ОТ ПЛОЩАДИ, А НЕ ОТ ШИРИНЫ. Поле меняется по обеим осям и непропорционально: на SE оно
    и уже, и заметно ниже. Множитель по одной стороне раздул бы пузыри на узком высоком экране,
    а корень из отношения площадей держит ту же ДОЛЮ ЗАЛИВКИ, то есть ту же плотность — а густота
    как раз и есть то, что делало поле кашей.
  */
  const k = clamp(Math.sqrt((fieldW * fieldH) / (350 * 500)), 0.8, 1.25);
  const rootSize = Math.round(ROOT_SIZE * k);
  const leafMin = Math.round(LEAF_MIN * k);
  const leafMax = Math.round(LEAF_MAX * k);
  const roots = ROOTS();
  const centers = rootCenters(roots.length);
  const byRoot = leavesByRoot();

  const out: Bubble[] = [];
  roots.forEach((root, i) => {
    const c = centers[i];
    out.push({ key: root.key, label: nodeLabel(root), root: root.key, kind: 'root',
               x: c.x, y: c.y, size: rootSize });
    const kids = byRoot.get(root.key) || [];
    /*
      СПУТНИКИ — НЕ КОЛЬЦОМ, А СВОЕЙ МАЛОЙ СПИРАЛЬЮ. Кольцо годилось, пока их было по шесть: два
      десятка на одной окружности встают вплотную, и разведение потом растаскивает их в кашу.
      Спираль по золотому углу раскладывает любое число ровным пятном без видимых рядов — тем же
      приёмом, что и центры категорий, только вокруг своего корня.
    */
    const spread = 0.10 + Math.min(kids.length, 24) * 0.0042;
    kids.forEach((kid, j) => {
      const a = i * 0.7 + j * GOLDEN;
      const rr = spread * Math.sqrt((j + 0.5) / Math.max(1, kids.length));
      // Размер убывает к концу списка: первые карточки категории заметнее, и глазу есть за что
      // зацепиться. Разброс небольшой — поле должно читаться полем, а не диаграммой.
      const t = kids.length > 1 ? j / (kids.length - 1) : 0;
      out.push({
        key: kid.key, label: kid.label, root: root.key, kind: 'leaf',
        x: c.x + Math.cos(a) * rr * 0.86,     // сжатие по x: экран уже, чем выше
        y: c.y + Math.sin(a) * rr,
        size: Math.round(leafMax - (leafMax - leafMin) * t),
      });
    });
  });
  return settle(out, fieldW, fieldH);
}

/**
 * РАЗВЕДЕНИЕ. Спираль ставит центры ровно, но кольца у разных категорий разной толщины: у спорта
 * девять спутников, у «дела» один — и соседние кусты налезают друг на друга. Замерено на первой
 * же раскладке: тридцать четыре перекрытия, худшее на тридцать шесть пикселей, то есть пузырь
 * целиком под пузырём.
 *
 * Поэтому пары, которые пересеклись, расталкиваются вдоль своей оси на половину нахлёста каждая,
 * и так несколько проходов. Порядок пар фиксирован, случайности нет — раскладка обязана быть
 * одинаковой при каждом открытии: человек, вернувшийся на шаг назад, ищет пузырь там, где видел.
 *
 * Считаем в ПИКСЕЛЯХ опорного поля, а не в долях: доли по x и y неравны (350 против 500), и
 * «расстояние» в них — не расстояние, а эллипс, из-за которого разведение по вертикали работало
 * бы вдвое слабее.
 */
/*
 * РАЗМЕР ПОЛЯ ПРИХОДИТ СНАРУЖИ, И ЭТО НЕ ПРИДИРКА К ЧИСТОТЕ.
 *
 * Раньше здесь стояли константы 350x500, а компонент рисовал в 330x430. Доли, посчитанные в одном
 * поле, растягивались по другому: x умножался на 0.943, y на 0.860 — сжатие неравное, значит
 * расстояния между центрами менялись по-разному, и разведение, ради которого написан весь `settle`,
 * обнулялось. Пересчитано: в опорных 350x500 наложений нет вовсе, а в фактических 330x430 их
 * девятнадцать, плюс шестьдесят три пары ближе того самого просвета, который код объявляет
 * обязательным, и один спутник вылезает за край.
 *
 * Поэтому раскладку считают ровно в тех точках, в которых её покажут.
 */
const GAP = 5;                    // просвет между краями соседних пузырей
const PASSES = 60;

function settle(bubbles: Bubble[], FIELD_W: number, FIELD_H: number): Bubble[] {
  const px = bubbles.map((b) => ({ ...b, px: b.x * FIELD_W, py: b.y * FIELD_H }));
  for (let pass = 0; pass < PASSES; pass++) {
    let moved = false;
    for (let i = 0; i < px.length; i++) {
      for (let j = i + 1; j < px.length; j++) {
        const a = px[i], b = px[j];
        let dx = b.px - a.px, dy = b.py - a.py;
        let d = Math.hypot(dx, dy);
        const need = (a.size + b.size) / 2 + GAP;
        if (d >= need) continue;
        // Совпавшие центры разводим по фиксированной оси, иначе деление на ноль и оба стоят.
        if (d < 0.001) { dx = 1; dy = 0; d = 1; }
        const push = (need - d) / 2;
        const ux = (dx / d) * push, uy = (dy / d) * push;
        // Категорию двигаем вдвое слабее: вокруг неё стоит её же кольцо, и уводя центр, мы
        // тянем за собой весь куст.
        const wa = a.kind === 'root' ? 0.5 : 1;
        const wb = b.kind === 'root' ? 0.5 : 1;
        a.px -= ux * wa; a.py -= uy * wa;
        b.px += ux * wb; b.py += uy * wb;
        moved = true;
      }
    }
    for (const b of px) {
      b.px = clamp(b.px, b.size / 2 + 2, FIELD_W - b.size / 2 - 2);
      b.py = clamp(b.py, b.size / 2 + 2, FIELD_H - b.size / 2 - 2);
    }
    if (!moved) break;
  }
  return px.map(({ px: X, py: Y, ...b }) => ({ ...b, x: X / FIELD_W, y: Y / FIELD_H }));
}

const clamp = (v: number, lo: number, hi: number) => Math.max(lo, Math.min(hi, v));
