/**
 * Дуговая карусель — колесо картинок по центру пустой главной.
 *
 * Одна картинка крупно посередине, соседние съезжают по дуге вниз, разворачиваются и уходят за
 * края экрана — видно только по кромке. Листается пальцем и защёлкивается на ближайшей, как
 * барабан в системных выборах iOS.
 *
 * ПОЧЕМУ ЭТО ScrollView, А НЕ СВОЙ ЖЕСТ. Магнит, инерция, отскок у края и подхват на лету — всё
 * это в `ScrollView` уже есть и сделано системой: `snapToInterval` вместе с `decelerationRate
 * fast` дают ровно то самое «щёлкает на место», которое в iOS ощущается родным. Своя реализация
 * на PanResponder повторяла бы физику приблизительно, и разница чувствуется сразу.
 *
 * ВСЯ ГЕОМЕТРИЯ — ИНТЕРПОЛЯЦИЯ ОДНОГО ЗНАЧЕНИЯ. Положение каждой картинки на дуге это функция
 * общего сдвига ленты: у каждой свой диапазон, вершина которого приходится на момент, когда она
 * оказывается по центру. Поэтому всё живёт на нативном драйвере и JS во время движения не
 * участвует — тот же приём, что у бегущих строк на экране входа.
 *
 * КОЛЕСО БЕСКОНЕЧНОЕ, И ЭТО СДЕЛАНО ПОВТОРОМ. Набор выложен трижды подряд, лента стартует со
 * средней копии, а на подходе к краю сдвиг перекидывается на длину набора без анимации. В этот
 * момент на экране стоит точно такая же картинка, поэтому подмены не видно. Одной копии не
 * хватило бы: у настоящего `ScrollView` есть край, и он бы упирался.
 */
import React, { useEffect, useMemo, useRef, useState } from 'react';
import {
  Animated,
  Image,
  ScrollView,
  ImageSourcePropType,
  NativeScrollEvent,
  NativeSyntheticEvent,
  Pressable,
  StyleSheet,
  Text,
  View,
  useWindowDimensions,
} from 'react-native';
import type { Glow } from './Ambient';
import { hStrong, hTick } from '../haptics';
import { color, displayFamily, space, type } from '../theme';
import { useLang } from '../i18n';

export type ArcItem = {
  key: string;
  source: ImageSourcePropType;
  /** Предложение под картинкой: «Побегаем?». Не название предмета — см. src/wheel.ts. */
  label: string;
  /** Что уйдёт в разговор, если по предмету нажать: «Хочу побегать». */
  query: string;
  /** Пятна подложки, пока этот предмет по центру. Разница между наборами намеренно небольшая. */
  glows?: Glow[];
};

/**
 * Шаг между центрами.
 *
 * Считается по САМОМУ УЗКОМУ предмету, а не по стороне рамки. Картинки вписываются по высоте, и у
 * вытянутых вверх (ракетка 276×366) ширина выходит вдвое меньше рамки; при шаге, подобранном под
 * квадрат, такая соседка не доставала до края экрана вовсе — колесо выглядело как одна картинка
 * посреди пустоты. С этим шагом из-за края видно около тридцати точек у самой узкой и вдвое
 * больше у широкой.
 */
const PITCH = 245;
/**
 * Сторона центральной картинки.
 *
 * Занимает почти всю ширину экрана — так и задумано: посреди пустой главной стоит один крупный
 * предмет, а не значок. Больше сделать нельзя: между шапкой и строкой «Чем хочешь заняться?»
 * остаётся около 580 точек, и в них должны уместиться и сама картинка, и съезд соседних по дуге.
 */
const BOX = 270;
/**
 * Во сколько раз мельче соседняя.
 *
 * Заметно мельче, чем в обычной карусели: при крупной центральной соседки того же размера лезли бы
 * на неё, а не выглядывали из-за края.
 */
const SIDE = 0.45;
/** Насколько соседняя съезжает вниз по дуге. Растёт вместе с картинкой: ей надо разойтись с ней. */
const LIFT = 70;
/** Наклон соседней — градусы. Дуга выпуклая вверх, поэтому правая клонится вправо. */
const TILT = 24;
/** Сколько копий набора выложено подряд. Три — минимум, при котором края не видно. */
const COPIES = 3;
/**
 * Шаг ленты наружу.
 *
 * Нужен тому, кто рисует фон: подложка меняется вместе с колесом, и её слои считают свою
 * непрозрачность от того же сдвига и с тем же шагом. Держать это число в двух местах значило бы
 * однажды подвинуть колесо и не заметить, что фон отстал на полкартинки.
 */
export const ARC_PITCH = PITCH;
/** Сколько копий набора в ленте — фону нужно знать, через сколько шагов предмет возвращается. */
export const ARC_COPIES = COPIES;
/** Высота подписи под картинкой вместе с отступом над ней. */
const CAP = 48;
/** Высота полосы: картинка, подпись, место, куда съезжают соседние, и запас под наклон. */
const BAND = BOX + CAP + LIFT + 24;

export function ArcCarousel({ items, onPick, progress }: {
  items: ArcItem[];
  /** Нажали по ТОЙ, что сейчас по центру. По соседней жест означает «подвинь её сюда». */
  onPick?: (item: ArcItem) => void;
  /**
   * Сдвиг ленты наружу — чтобы фон менялся вместе с колесом.
   *
   * Передаётся ГОТОВОЕ значение, а не колбэк с числом: колбэк означал бы кадр за кадром через
   * JS-поток, а так и колесо, и подложка читают одно и то же значение на стороне UI, и разъехаться
   * они не могут в принципе — даже на самом резком броске пальца.
   */
  progress?: Animated.Value;
}) {
  const lang = useLang();
  const { width } = useWindowDimensions();
  const n = items.length;
  /**
   * СДВИГ НАЧИНАЕТСЯ СО СТАРТОВОГО, А НЕ С НУЛЯ.
   *
   * `contentOffset` ставит ленту на середину набора БЕЗ события прокрутки — событий до касания не
   * будет вовсе. Значение, начатое с нуля, оставалось нулём, и первый кадр рисовался так, будто
   * по центру стоит самая первая картинка: та, что реально в центре, приезжала уменьшенной, а
   * соседних не было видно совсем. Заметно это только на первом кадре — до первого касания
   * пальцем, — и потому чинится ровно здесь.
   */
  const start = n * PITCH;
  const own = useRef(new Animated.Value(start)).current;
  const x = progress ?? own;
  // Переданное снаружи значение начинается с нуля — ставим его на середину набора, как своё.
  useEffect(() => {
    x.setValue(start);
  }, [x, start]);
  const list = useRef<ScrollView>(null);
  const [at, setAt] = useState(n);

  /** Лента: набор, повторённый трижды. Ключи разные — иначе React сочтёт копии одним элементом. */
  const strip = useMemo(
    () =>
      Array.from({ length: n * COPIES }, (_, i) => ({
        ...items[i % n],
        key: `${items[i % n].key}#${Math.floor(i / n)}`,
      })),
    [items, n]
  );

  const onScroll = Animated.event([{ nativeEvent: { contentOffset: { x } } }], {
    useNativeDriver: true,
    /*
      Щелчок при смене центральной. Считается ЦЕЛЫМ ДЕЛЕНИЕМ и сравнением с прошлым — на кадр это
      одно деление и одно сравнение, поэтому обработчик можно держать на каждом кадре прокрутки,
      не мешая ей. Без щелчка колесо крутится молча и на ощупь ничем не отличается от обычной
      прокрутки; с ним чувствуется, что оно защёлкивается по одной.
    */
    listener: (e: NativeSyntheticEvent<NativeScrollEvent>) => {
      const i = Math.round(e.nativeEvent.contentOffset.x / PITCH);
      if (i !== at) {
        setAt(i);
        hTick();
      }
    },
  });

  /** Перекидываем ленту на копию назад или вперёд, когда подошли к краю. */
  const wrap = (e: NativeSyntheticEvent<NativeScrollEvent>) => {
    const cur = e.nativeEvent.contentOffset.x;
    const span = n * PITCH;
    if (cur < span * 0.5) list.current?.scrollTo({ x: cur + span, animated: false });
    else if (cur > span * 2.5) list.current?.scrollTo({ x: cur - span, animated: false });
  };

  return (
    <View style={s.wrap} pointerEvents="box-none">
      <Animated.ScrollView
        ref={list as any}
        horizontal
        style={s.strip}
        showsHorizontalScrollIndicator={false}
        // Магнит: лента останавливается только на шаге, а не там, где кончилась инерция.
        snapToInterval={PITCH}
        decelerationRate="fast"
        contentOffset={{ x: start, y: 0 }}
        contentContainerStyle={{ paddingHorizontal: (width - PITCH) / 2 }}
        onScroll={onScroll}
        onMomentumScrollEnd={wrap}
        scrollEventThrottle={16}
      >
        {strip.map((it, i) => {
          /*
            Сдвиг, при котором эта картинка стоит по центру экрана. Ниже все три превращения
            выражены через диапазон вокруг него: слева от центра, в центре, справа от центра.
          */
          const mid = i * PITCH;
          const range = [mid - PITCH, mid, mid + PITCH];
          const scale = x.interpolate({
            inputRange: range,
            outputRange: [SIDE, 1, SIDE],
            extrapolate: 'clamp',
          });
          const y = x.interpolate({
            inputRange: range,
            outputRange: [LIFT, 0, LIFT],
            extrapolate: 'clamp',
          });
          const rotate = x.interpolate({
            inputRange: range,
            // Дуга выпуклая вверх: та, что ещё справа, наклонена по часовой, ушедшая влево — против.
            outputRange: [`${TILT}deg`, '0deg', `${-TILT}deg`],
            extrapolate: 'clamp',
          });
          const opacity = x.interpolate({
            inputRange: range,
            outputRange: [0.8, 1, 0.8],
            extrapolate: 'clamp',
          });
          return (
            <Animated.View
              key={it.key}
              style={[s.slot, { opacity, transform: [{ translateY: y }, { rotate }, { scale }] }]}
            >
              {/*
                ДВА РАЗНЫХ ЖЕСТА ОДНИМ НАЖАТИЕМ, и различает их положение предмета.

                По соседней — «подвинь её сюда»: она наполовину за краем экрана, тянуться к ней
                пальцем неудобно, и нажатие по ней очевидно означает выбор, а не запуск.

                По центральной — «поехали»: разговор открывается с уже сказанной фразой. Отклик
                тут тяжёлый, а не обычный: экран меняется целиком, и рука должна это отметить.
              */}
              <Pressable
                accessibilityRole="button"
                accessibilityLabel={it.label}
                onPress={() => {
                  if (i === at && onPick) {
                    hStrong();
                    onPick(it);
                    return;
                  }
                  list.current?.scrollTo({ x: mid, animated: true });
                }}
              >
                <Image
                  accessibilityIgnoresInvertColors
                  source={it.source}
                  style={s.pic}
                  resizeMode="contain"
                />
                {/*
                  Подпись едет вместе с картинкой — она часть предмета, а не строка под колесом.
                  Отдельной строкой под лентой она стояла бы на месте, пока предмет уезжает, и
                  на середине жеста подписывала бы уже не то, что видно.
                */}
                <Text style={[s.cap, { fontFamily: displayFamily(lang) }]} numberOfLines={1}>
                  {it.label}
                </Text>
              </Pressable>
            </Animated.View>
          );
        })}
      </Animated.ScrollView>
    </View>
  );
}

// ===== вид
const s = StyleSheet.create({
  /*
    ВЫСОТА ЗАДАНА ЯВНО НА ВСЕХ ТРЁХ СЛОЯХ, И ЭТО НЕ ПЕДАНТИЗМ. Пока её считали по содержимому,
    горизонтальная прокрутка получала высоту от родителя, а не от картинки: при рамке 430 предмет
    выходил 295 точек, то есть на треть мельче заданного, а соседние вылезали за низ и обрезались.
    Три явных числа убирают догадки: полоса, прокрутка и ячейка одной высоты.

    Ячейка выше картинки на величину съезда: соседние уезжают вниз на LIFT, и это место надо
    заранее оставить — прокрутка обрезает всё, что вышло за её край, а `overflow: visible` на ней
    не работает.
  */
  wrap: { height: BAND, justifyContent: 'center' },
  strip: { height: BAND },
  /** Ячейка ровно в шаг ленты: от этого зависит, что центр ячейки совпадает с центром экрана. */
  slot: { width: PITCH, height: BAND, alignItems: 'center', justifyContent: 'flex-start' },
  cap: { ...type.wheelLabel, color: color.fg, textAlign: 'center', marginTop: space.md } as any,
  /*
    ТЕНИ У КАРТИНКИ НЕТ, И ЭТО НЕ ЗАБЫЛИ. Она тут была — мягкая, чтобы предмет не висел плоской
    наклейкой. Но iOS рисует тень по ПРЯМОУГОЛЬНИКУ вида, а не по прозрачности картинки внутри
    него: вокруг вишни появлялась отчётливая светлая рамка размером с кадр. На мелком размере её
    было почти не видно, на крупном она читается сразу.
    Правильная тень тут — часть самой картинки: у предметов в наборе она уже нарисована.
  */
  pic: { width: BOX, height: BOX },
});
