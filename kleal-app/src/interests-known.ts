/**
 * Знает ли приложение этот ключ САМО.
 *
 * ЗАЧЕМ ОТДЕЛЬНАЯ ПРОВЕРКА, если есть серверная. Онбординг с 27.08 сверяет каждый интерес с общей
 * таксономией и отклоняет ВЕСЬ вызов `register`, если хоть один ключ ей неизвестен. Узнать это с
 * телефона нельзя — каталог живёт на сервере. Но одну половину можно решить не спрашивая: словарь,
 * которым оперирует само приложение (дерево колеса плюс колода карточек), сервер принимает целиком.
 * Проверено запросом к живому нормализатору: 326 ключей, отклонённых ноль; сторож
 * `tools/interest_keys_test.js` держит это свойство.
 *
 * Отсюда правило: ключ из своего словаря пишем сразу, как писали всегда. Всё остальное — слова,
 * которые человек придумал сам, — идёт через подтверждение, потому что записать их вслепую значит
 * привести человека к «Профиль не сохранился» в конце анкеты.
 */
import { WHEEL_TREE, type WheelNode } from './interests-wheel';
import { DECK } from './interests-deck';
import { OFF_TAXONOMY } from './mindmap';

let known: Set<string> | null = null;

function collect(nodes: WheelNode[], out: Set<string>): void {
  for (const n of nodes) {
    out.add(n.key.toLowerCase());
    if (n.kids?.length) collect(n.kids, out);
  }
}

/**
 * Ключ из собственного словаря приложения — дерева или колоды.
 *
 * Считается один раз: состав не меняется в течение запуска, а зовут это на каждый ход агента.
 * Колода читается через `DECK()`, потому что подписи в ней зависят от языка, а ключи — нет.
 */
export function isKnownInterest(key: string): boolean {
  const k = String(key || '').trim().toLowerCase();
  if (!k) return false;
  if (!known) {
    known = new Set<string>();
    collect(WHEEL_TREE, known);
    /*
      КОЛОДА ИДЁТ БЕЗ ТЕХ, КОГО В ОБЩЕЙ ТАКСОНОМИИ НЕТ, и это исправление собственной ошибки.
      Сначала сюда попадала вся колода целиком — а в ней четыре карточки («Боулинг», «Бильярд»,
      «Подкасты», «Море»), которым узла не завели. Признав их своими, анкета писала их в профиль
      без подтверждения, и на сводке человек упирался в «Профиль не сохранился: Kleal пока не знает
      такие интересы — bowling» без всякого выхода. Поймано на живом прогоне.

      Своим считается только то, что сервер точно примет. Эти четыре пойдут обычным путём —
      через предложение и подтверждение, как любое придуманное слово.
    */
    const off = new Set(OFF_TAXONOMY.map((k) => k.toLowerCase()));
    for (const c of DECK()) {
      const k = c.key.toLowerCase();
      if (!off.has(k)) known.add(k);
    }
  }
  return known.has(k);
}
