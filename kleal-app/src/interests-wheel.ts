import { T } from './i18n';

export type WheelNode = {
  /** Канонический английский ключ — то, что ложится в interests и по чему ищет матчинг. */
  key: string;
  ru: string;
  en: string;
  /** Испанская подпись. Приходит из того же реестра, что русская и английская. */
  es: string;
  /** Только у первого уровня — имя контурной иконки из components/category-icons. */
  icon?: string;
  kids?: WheelNode[];
};

const N = (key: string, ru: string, en: string, es: string, kids?: WheelNode[]): WheelNode =>
  ({ key, ru, en, es, kids });
const TOP = (key: string, ru: string, en: string, es: string, icon: string, kids: WheelNode[]): WheelNode =>
  ({ key, ru, en, es, icon, kids });

/*
  ДЕРЕВО БОЛЬШЕ НЕ ЖИВЁТ ЗДЕСЬ. Оно генерируется из общего с сервером реестра —
  kleal-ms/shared/interests.json — и лежит в interests-tree.generated.ts.

  Пока литерал был здесь, источников было два: сервер знал 447 ключей, карта 320. Сто двадцать
  восемь занятий поиск понимал, а выбрать их на экране было нельзя, и добавить интерес значило
  дописать его в двух местах — что рано или поздно расходится. Так уже случилось с зеркалом
  таксономии в buddy: оно отстало на 283 слова, и никто этого не заметил.

  Добавить интерес теперь: строка в shared/interests.json, потом
  python3 kleal-ms/tools/gen_interests_tree.py --apply
*/
import { TREE } from './interests-tree.generated';

export const WHEEL_TREE: WheelNode[] = TREE;

export const nodeLabel = (n: WheelNode) => T(n.ru, n.en, n.es);

/** Подпись по ключу — для чипов собранного. Не нашли в дереве — значит слово человека, как есть. */
export function labelOf(key: string): string {
  const walk = (list: WheelNode[]): string | null => {
    for (const n of list) {
      if (n.key === key) return nodeLabel(n);
      const deep = n.kids ? walk(n.kids) : null;
      if (deep) return deep;
    }
    return null;
  };
  return walk(WHEEL_TREE) || key;
}

/**
 * Из добавленных ключей — те, про которые стоит РАЗГОВАРИВАТЬ: без предков более точного выбора.
 * «sports, racket, padel» → разговор про падел; спрашивать «чем тебе нравится спорт» после этого —
 * значит показать, что ответа не услышали. Ключ, добавленный БЕЗ уточнения («Спорт» и всё),
 * остаётся: это и есть выбор человека.
 */
export function funnelWorthy(keys: string[]): string[] {
  const anc = new Set<string>();
  const walk = (list: WheelNode[], path: string[]) => {
    for (const n of list) {
      if (keys.includes(n.key)) path.forEach((p) => anc.add(p));
      if (n.kids) walk(n.kids, [...path, n.key]);
    }
  };
  walk(WHEEL_TREE, []);
  return keys.filter((k) => !anc.has(k));
}

