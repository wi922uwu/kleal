/**
 * ШРИФТЫ. Оба из борда и оба лежат в `assets/fonts`, грузятся в `app/_layout.tsx`.
 *
 * `display` — Special Gothic Expanded One: широкий гротеск, которым набраны все заголовки
 * входных экранов. Именно он делает узнаваемым первый экран, поэтому подобрать системным
 * нельзя — ни один системный не расширен так.
 *
 * `text` — Geist: весь остальной текст. У него три начертания, и в RN каждое начертание это
 * ОТДЕЛЬНОЕ семейство: `fontWeight` на подключённом файле не работает, поэтому ниже везде
 * указывается семейство целиком, а не вес.
 */
