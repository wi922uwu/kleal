/**
 * ЗАГОЛОВОЧНЫЙ ШРИФТ ВЫБИРАЕТСЯ ПО ЯЗЫКУ, и это вынужденно.
 *
 * В Special Gothic Expanded One НЕТ НИ ОДНОЙ кириллической буквы — проверено по таблице глифов
 * файла: латиница 58 из 58, кириллица 0 из 64. Борд рисовали по-английски, и там это не видно;
 * в двуязычном приложении русский заголовок молча уезжал в системный шрифт, а латинские слова в
 * той же строке оставались фирменными. На экране это выглядело как две разные гарнитуры в одном
 * предложении: «Скажи Kleal, чем хочешь заняться».
 *
 * Пока для русского нет своего широкого гротеска, он набирается Geist Semibold: он уже загружен,
 * покрывает кириллицу целиком и даёт ОДНУ гарнитуру на всю строку вместо двух. Это подмена, а не
 * решение — заменить её на настоящий кириллический дисплейный шрифт можно правкой одной строки
 * здесь, и больше нигде.
 */
export const displayFamily = (lang: string) => (lang === 'ru' ? font.textSemibold : font.display);

