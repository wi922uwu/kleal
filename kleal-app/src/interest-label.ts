/**
 * ОДНА ПОДПИСЬ ИНТЕРЕСА НА ВСЁ ПРИЛОЖЕНИЕ.
 *
 * Зачем отдельный файл, если функции локализации уже есть. Их было ДВЕ, и они не знали друг о
 * друге:
 *
 *   `labelOf`   (src/interests-wheel.ts) — дерево колеса, 312 ключей, у каждого ru и en;
 *   `hobbyPlain`(src/onboarding.ts)      — десять встроенных увлечений.
 *
 * Полная жила ровно на одном экране — чипы под колесом в онбординге. Всё остальное ходило через
 * `hobbyPlain`, у которого при промахе `return k`: ключ печатался сырым. Человек, выбравший
 * «Спорт → Ракетки → Падел», видел в профиле, в выдаче и на карточках три строки «sports»,
 * «racket», «padel» — и они не менялись при переключении языка, потому что переводить было
 * нечем (сообщено с телефона 14 августа: «создаю интерес на английском, переключаюсь на русский
 * — интерес остался на английском»).
 *
 * ЛЕСЕНКА, а не один словарь. Ключи приходят из трёх разных мест, и ни одно не покрывает
 * остальные:
 *
 *   0. подписи с сервера  — общий словарь interest_i18n (см. ниже), главный источник;
 *   1. дерево колеса      — ключи подборщика, которого больше нет; лежат в старых профилях;
 *   2. колода интересов   — 36 карточек, из которых собрана карта онбординга;
 *   3. встроенные HOBBIES — десять чипов первого шага онбординга;
 *   4. сырой текст        — написанное руками, ещё не переведённое.
 *
 * КОЛОДА ПОЯВИЛАСЬ ЗДЕСЬ ПОЗЖЕ ОСТАЛЬНЫХ, и по той же причине, по которой заведён весь файл.
 * Часть её ключей дерево колеса не знает — оно старше. Пока подписи брались только оттуда, человек
 * выбирал на карте «Языки» и «Танцы», а под картой и дальше в профиле у него стояли `languages` и
 * `dancing`: карта рисует подпись из карточки, а всё остальное приложение спрашивало словарь,
 * которому этих ключей не давали. Поймано на симуляторе на трёх выбранных пузырях.
 *
 * Третья ступень когда-то была ответом «это человек написал сам, такое не переводится». Теперь
 * переводится: ключ в профиле английский, а подпись на языке человека приходит с сервера нулевой
 * ступенью. Сюда доходит только то, что сервер ещё не успел выучить, — и показать своё слово
 * лучше, чем пустоту.
 *
 * ПОЧЕМУ НЕ РЕЗОЛВИМ ТЕКСТ В УЗЕЛ ЗДЕСЬ. Резолв «написанное словами → узел таксономии» живёт на
 * сервере (matching_core/canonical.py): там не просто поиск по словарю, а правило префиксов с
 * порогами длины, которое уже правили из-за ложных срабатываний. Второй такой же разбор на
 * клиенте разошёлся бы с серверным при первой правке таксономии — и разошёлся бы молча: человек
 * видел бы себя, а матчинг его не находил. Здесь только ПОДПИСЬ по известному ключу.
 */
import { labelOf } from './interests-wheel';
import { hobbyPlain } from './onboarding';
import { DECK } from './interests-deck';
import { getLang } from './i18n';

/**
 * НУЛЕВАЯ СТУПЕНЬ — ПОДПИСИ С СЕРВЕРА. Интересы теперь хранятся английскими ключами, а их
 * переводы живут в общем серверном словаре (shared/interest_i18n.py): сервер кладёт словарь
 * `interestLabels` рядом с профилем и с выдачей кандидатов, а api.ts сгружает его сюда. Реестр
 * ведётся ПО ЯЗЫКАМ: после переключения языка подписи прошлого языка не годятся, и до следующего
 * запроса работает обычная лесенка ниже (у колеса свои ru/en на все 312 ключей).
 *
 * Реестр — на устройстве и на сессию, не хранилище: правда живёт на сервере, здесь только кэш
 * последнего ответа.
 */
const serverLabels: Record<string, Record<string, string>> = { ru: {}, es: {} };

/** Сгрузить словарь подписей из ответа сервера. Зовёт api.ts; экраны об этом не знают. */
export function registerInterestLabels(map: unknown, lang: string): void {
  const bucket = serverLabels[lang];
  if (!bucket || !map || typeof map !== 'object') return;
  for (const [k, v] of Object.entries(map as Record<string, unknown>)) {
    if (typeof v === 'string' && v.trim()) bucket[k.trim().toLowerCase()] = v.trim();
  }
}

/**
 * Подписи колоды на текущем языке. Пересобираются при смене языка: `DECK()` зовёт `T`, поэтому
 * один раз посчитанный словарь после переключения показывал бы прошлый язык.
 */
let deckCache: { lang: string; map: Record<string, string> } | null = null;
function deckLabel(k: string): string | null {
  const lang = getLang();
  if (!deckCache || deckCache.lang !== lang) {
    const map: Record<string, string> = {};
    for (const c of DECK()) map[c.key.toLowerCase()] = c.label;
    deckCache = { lang, map };
  }
  return deckCache.map[k.toLowerCase()] || null;
}

/** Подпись интереса на текущем языке. Неизвестный ключ возвращается как есть — это своё слово. */
export function interestLabel(key: string): string {
  const k = String(key || '').trim();
  if (!k) return '';
  const srv = serverLabels[getLang()]?.[k.toLowerCase()];
  if (srv) return srv;
  const wheel = labelOf(k);
  if (wheel !== k) return wheel;
  const deck = deckLabel(k);
  if (deck) return deck;
  const hobby = hobbyPlain(k);
  if (hobby !== k) return hobby;
  return k;
}

/** Список подписей: пустые и повторы убираются, порядок сохраняется. */
export function interestLabels(keys: string[] | undefined | null): string[] {
  const out: string[] = [];
  for (const k of keys || []) {
    const label = interestLabel(k);
    if (label && !out.includes(label)) out.push(label);
  }
  return out;
}
