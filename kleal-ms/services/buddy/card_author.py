"""КАРТОЧКУ СОБИРАЕТ МОДЕЛЬ, А КОД ОСТАЁТСЯ СТОРОЖЕМ.

ЗАЧЕМ ЭТОТ МОДУЛЬ ВООБЩЕ ПОЯВИЛСЯ. К 22.09.2026 разбор ответа модели состоял из сотен
регулярных выражений: падежи, глаголы по занятию, стоп-слова, сита предмета. Каждую ночь
добавлялась ещё одна, а общий счёт бед за круг стоял на месте тридцать часов (159 -> 159).
Прямая проверка показала, почему: модель НЕ ошибается там, где ошибается продукт.

    «в падел кто тут играет»              -> модель: «Падел.»   продукт: «Поиграть в играет»
    «думал в кино, хотя не, лучше в бар»  -> модель: «Бар.»      продукт: «Посмотреть кино»

То есть понимание уже есть, и теряет его наш собственный слой ПОСЛЕ модели. Опыт на 132 живых
разговорах одной меркой: сегодняшний путь 0.712 бед, этот путь 0.273. Починено 63, сломано 5.

ЧТО ПОКАЗАЛИ ТЕ ПЯТЬ. Модель слишком услужлива: на «мне 15, хочу гулять» она открыла поиск
людей, на выдуманное «заркибола» сочинила занятие, на одинокое «спиннеры» — тоже. Поэтому
вывод опыта не «отдать всё модели», а «модель автор, код сторож», и сторожей нужно немного,
но жёстких. Здесь их ровно три, и каждый закрывает один из этих трёх случаев.

ЧЕГО ЗДЕСЬ НАРОЧНО НЕТ. Ни падежей, ни таблиц глаголов, ни стоп-списков — всё это и есть тот
слой, ради ухода от которого модуль написан. Если тянет добавить сюда регулярку про склонение,
значит место выбрано неверно: правь промпт.
"""
import io, json, os, re

КОРЕНЬ = os.environ.get("KLEAL_ROOT") or "/opt/kleal/kleal-ms"
_словарь = None
_подписи = None


def словарь():
    """Ключи реестра — единственное, что модели позволено класть в чипы."""
    global _словарь, _подписи
    if _словарь is None:
        рег = json.load(io.open(os.path.join(КОРЕНЬ, "shared", "interests.json"), encoding="utf-8"))
        дер = рег.get("tree", рег)
        ключи = set()

        def обойти(у):
            if isinstance(у, dict):
                for k, v in у.items():
                    ключи.add(k)
                    обойти(v)
            elif isinstance(у, list):
                for v in у:
                    if isinstance(v, str):
                        ключи.add(v)
                    else:
                        обойти(v)
        обойти(дер)
        _словарь = {k for k in ключи if isinstance(k, str) and len(k) > 1}
        л = рег.get("labels") or {}
        _подписи = {}
        if isinstance(л, dict):
            for k, v in л.items():
                _подписи[k] = [str(x).lower() for x in (v.values() if isinstance(v, dict) else [v]) if x]
    return _словарь


def подписи(ключ):
    словарь()
    return (_подписи or {}).get(ключ, [])


# СТОРОЖ 1: ВОЗРАСТ. Человеку младше 18 поиск людей не открываем никогда — это решение продукта,
# а не модели, и услужливая модель его переступает (проверено: «мне 15, хочу гулять» -> попап).
_РЕБЁНОК = re.compile(
    r"(?iu)(?:^|\W)(?:мне|мне\s+уже|ему|ей|i\s*'?\s*m|im|i\s+am|tengo)\s*"
    r"(?:всего\s+)?(?:[89]|1[0-7])\s*(?:лет|года?|годиков|years?\s*old|years|a[nñ]os?)?(?:\W|$)")


def ребёнок(реплики):
    return bool(_РЕБЁНОК.search(" ".join(str(x or "") for x in (реплики or []))))


# СТОРОЖ 2: ЗОВУТ ЛИ ЛЮДЕЙ. Модель считает заявкой почти всё; продукт открывает поиск только
# тогда, когда человек либо назвал занятие, которое мы знаем, либо прямо позвал людей.
_ПРИЗЫВ = re.compile(
    r"(?iu)(?:с\s+кем|кто\s+со\s+мной|кто\s+(?:нибудь|тут|здесь|хочет|пойд[её]т|играет|ходит)|"
    r"ищу\s+(?:компани|кого|人)|нужн[аы]?\s+(?:компани|партн[её]р|кто)|состав\w*\s+компани|"
    r"вдво[её]м|вместе|присоедин\w*|"
    r"anyone|any\s?one|somebody|someone|who\s+(?:wants|else|is\s+up)|looking\s+for\s+(?:company|people|someone)|"
    r"join\s+me|with\s+me|together|"
    r"alguien|busco\s+(?:gente|compa|alguien)|con\s+qui[eé]n|juntos|acompa[nñ]\w*)")


def зовут_людей(реплики):
    return bool(_ПРИЗЫВ.search(" ".join(str(x or "") for x in (реплики or []))))


def опора_в_реестре(реплики, свести=None):
    """Есть ли в сказанном хоть одно слово, которое реестр знает.

    Без опоры и без призыва «спиннеры» и «заркибола» превращались моделью в занятие.
    `свести` — резолвер продукта (norm_topic); передаётся снаружи, чтобы модуль не тянул app.
    """
    слова = re.findall(r"(?iu)[\wЀ-ӿ]{3,}", " ".join(str(x or "") for x in (реплики or [])))
    низ = словарь()
    for w in слова:
        if w.lower() in низ:
            return True
        if свести:
            try:
                if свести(w):
                    return True
            except Exception:
                pass
    return False


ЯЗЫК = {"ru": "по-русски", "en": "in English", "es": "en español"}

ПРОМПТ = u"""Ты собираешь карточку встречи для приложения Kleal по репликам человека.

ВОТ ВЕСЬ СЛОВАРЬ ИНТЕРЕСОВ (только эти слова можно класть в chips):
%s

ПРАВИЛА.
1. is_request = true только если человек хочет ЧЕМ-ТО ЗАНЯТЬСЯ С ДРУГИМИ ЛЮДЬМИ.
   Разговор с самим ассистентом (о нём, личное, романтическое), жалоба без заявки,
   пустая реплика, одно слово без просьбы — это false.
2. chips — от одного до трёх слов ТОЛЬКО из словаря выше, точным написанием.
   Никогда не клади туда настроение, время, место, компанию и слова, выдернутые из фразы.
   Если подходящего слова в словаре нет — верни chips пустым и is_request=false.
3. title — %s, коротко: ГЛАГОЛ + ПРЕДМЕТ. Предмет — это занятие или вещь, а НЕ слово из
   реплики человека наугад и НЕ глагол. Верно: «Выпить кофе», «Поиграть в настолки»,
   «Сходить на выставку». Неверно: «Поиграть в играет», «Сходить на пустой».
   Не пиши «Поговорить о…», если этим занятием можно заняться.
4. Если человек передумал («хотя нет», «лучше», «в итоге», "wait no", "instead", "mejor"),
   карточка про ПОСЛЕДНЕЕ названное занятие. Отменённое не должно появиться НИ в title,
   НИ в chips — нигде.
5. Если человек от чего-то отказался («не хочу бегать, а кофе давай», "but maybe not",
   "no me apetece"), отказ касается и chips тоже: отвергнутое слово в chips класть НЕЛЬЗЯ.
6. ПЕРЕД ОТВЕТОМ перечитай реплики и вычеркни из chips всё, от чего человек отказался или
   что он отменил. Чипы описывают то, чего человек хочет СЕЙЧАС, а не то, что он упоминал.

Ответь ТОЛЬКО одним JSON-объектом без пояснений:
{"is_request": true/false, "title": "...", "subject": "...", "chips": ["...", "..."]}"""


def _разобрать(текст):
    if not текст:
        return None
    м = re.search(r"\{.*\}", текст, re.S)
    if not м:
        return None
    for попытка in (м.group(0), re.sub(r",\s*}", "}", м.group(0))):
        try:
            return json.loads(попытка)
        except Exception:
            continue
    return None


def проверить(карточка):
    """Код — проверяющий, не автор: говорим модели, ЧТО не так, и даём один переспрос."""
    if not isinstance(карточка, dict):
        return [u"ответ не JSON"]
    if not карточка.get("is_request"):
        return []
    беды = []
    чипы = [c for c in (карточка.get("chips") or []) if isinstance(c, str)]
    чужие = [c for c in чипы if c not in словарь()]
    if чужие:
        беды.append(u"chips вне словаря: %s" % ", ".join(чужие[:3]))
    if not чипы:
        беды.append(u"chips пуст")
    заг = str(карточка.get("title") or "").strip()
    if not заг:
        беды.append(u"title пуст")
    elif len(заг.split()) < 2:
        беды.append(u"title без глагола и предмета: %r" % заг)
    return беды


def сторожа(реплики, карточка, свести=None):
    """Три жёстких правила поверх ответа модели. Возвращает (открывать_ли, причины)."""
    причины = []
    if not (карточка or {}).get("is_request"):
        причины.append(u"модель не считает это заявкой")
    if ребёнок(реплики):
        причины.append(u"рубеж возраста")
    if not (опора_в_реестре(реплики, свести) or зовут_людей(реплики)):
        причины.append(u"ни знакомого занятия, ни призыва к людям")
    return (not причины), причины


def собрать(реплики, lang="ru", модель=None, звонок=None, свести=None):
    """Полный путь: модель пишет карточку, код проверяет, при браке один переспрос, затем сторожа."""
    if звонок is None:
        from llm_client import llm_complete as звонок
    модель = модель or os.environ.get("V2_MODEL") or "qwen3_self"
    строки = "\n".join("- %s" % str(t) for t in (реплики or []))
    сообщения = [{"role": "system", "content": ПРОМПТ % (", ".join(sorted(словарь())), ЯЗЫК.get(lang, ЯЗЫК["en"]))},
                 {"role": "user", "content": u"Реплики человека подряд:\n%s" % строки}]
    карточка, беды, попыток = None, [u"нет ответа"], 0
    for _ in range(2):
        попыток += 1
        сырое = звонок(модель, сообщения, temperature=0, tag="card_author") or ""
        карточка = _разобрать(сырое)
        беды = проверить(карточка)
        if not беды:
            break
        сообщения = сообщения + [{"role": "assistant", "content": сырое[:600]},
                                 {"role": "user", "content": u"Не годится: %s. Исправь и верни только JSON." % "; ".join(беды)}]
    открывать, причины = сторожа(реплики, карточка or {}, свести)
    return {"открывать": открывать, "причины": причины, "попыток": попыток,
            "title": str((карточка or {}).get("title") or ""),
            "subject": str((карточка or {}).get("subject") or ""),
            "chips": [c for c in ((карточка or {}).get("chips") or []) if isinstance(c, str)],
            "брак_проверки": беды}
