# -*- coding: utf-8 -*-
"""Печать ответа Буди V2 по мере написания (17.10.2026) — _Поток и ход(on_text).

    python3 services/buddy/test_v2_stream.py

Модель подставная, кусками по несколько символов. Проверяется: на экран идут только законченные
предложения, прошедшие сита; вопрос, похвала и «ищу тебе…» не показываются до итога; показанное —
начало итогового ответа; маркер карточки и JSON не просачиваются; вторая попытка не печатается."""
import importlib.util
import json
import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
for _p in (_HERE, os.path.join(_HERE, "..", "..", "shared")):
    if os.path.isdir(_p) and _p not in sys.path:
        sys.path.insert(0, _p)
_spec = importlib.util.spec_from_file_location("buddy", os.path.join(_HERE, "app.py"))
B = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(B)
import v2 as V2

ok = fail = 0


def check(name, cond, detail=""):
    global ok, fail
    if cond:
        ok += 1
    else:
        fail += 1
        print("FAIL %-60s %s" % (name, str(detail)[:300]))


def U(t):
    return {"role": "user", "content": t}


def _к(title, chips, subject="", cat="other"):
    return '###CARD\n' + json.dumps({"card": {"title": title, "subject": subject, "role": "play", "chips": chips,
                                                "category": cat, "request": True}}, ensure_ascii=False)


_НЕТ = '###CARD\n{"card": null}'


def ход(ответы, msgs, сборщик=False, шаг=3):
    """-> (итог ход(), показанные куски, вызовы потока, вызовы целиком)."""
    ответы = list(ответы)
    куски, вызовы = [], {"поток": 0, "целиком": 0}
    было_c, было_s = B.llm_complete, B.llm_stream

    def целиком(model, messages, **kw):
        вызовы["целиком"] += 1
        return ответы.pop(0) if len(ответы) > 1 else ответы[0]

    def поток(model, messages, temperature, field, on_text, gate=None, tag=""):
        вызовы["поток"] += 1
        assert field is None
        сырое = ответы.pop(0) if len(ответы) > 1 else ответы[0]
        for i in range(0, len(сырое), шаг):
            on_text(сырое[i:i + шаг])
        return сырое

    B.llm_complete, B.llm_stream = целиком, поток
    try:
        r = V2.ход(msgs, {"name": "Иван", "age": 30}, {}, "ru", B, сборщик=сборщик, on_text=куски.append)
    except RuntimeError as e:
        r = ("RAISE", str(e))
    finally:
        B.llm_complete, B.llm_stream = было_c, было_s
    return r, "".join(куски), вызовы


def норм(s):
    return " ".join(str(s or "").split())


# 1. Болтовня без карточки: всё повествовательное печатается по ходу, хвостовой вопрос — только в итоге.
r, показано, в = ход(["Понимаю, после долгой недели хочется просто выдохнуть. Можно никуда не спешить и "
                      "провести вечер спокойно. Как прошёл день?\n" + _НЕТ], [U("устал как собака")])
check("болтовня: показано до вопроса", показано.startswith("Понимаю, после долгой недели") and "?" not in показано, показано)
check("болтовня: показанное — начало итога", норм(r[0]).startswith(норм(показано)) and показано, (показано, r[0]))
check("болтовня: один вызов, потоком", в == {"поток": 1, "целиком": 0}, в)

# 2. Маркер карточки и JSON не просачиваются, даже если в последнем куске маркер склеен с текстом.
r, показано, _ = ход(["Сегодня вечером в городе тихо, можно просто прогуляться.\n###CARD\n{\"card\": null}"],
                     [U("что делать вечером")], шаг=7)
check("маркер: нет ### и {", "#" not in показано and "{" not in показано, показано)
check("маркер: предложение перед маркером показано", "прогуляться." in показано, показано)

# 3. Похвала первым предложением — поток молчит, ничего не печатается, итог как раньше.
r, показано, _ = ход(["Кофе — отличная идея! Давай посмотрим, кто рядом.\n" + _к("Выпить кофе", ["coffee"], "кофе", "coffee")],
                     [U("хочу выпить кофе с кем нибудь")])
check("похвала: ничего не показано", показано == "", показано)
check("похвала: затея есть", r[1] and "coffee" in (r[1].get("topics") or []), r)

# 4. Заявление «ищу тебе компанию» не печатается.
r, показано, _ = ход(["Ищу тебе компанию на каток!\n" + _НЕТ], [U("люблю кататься на коньках")])
check("заявление: не показано", "Ищу" not in показано, показано)

# 5. Брак первой попытки -> вторая целиком, без печати; показанное (если было) — не длиннее итога по смыслу.
r, показано, в = ход(["Помогу найти партнёра на кофе!\n" + _к("Поиграть в майнкрафт", ["minecraft"]),
                      "Кофе вдвоём — это приятно. Какой любишь?\n" + _НЕТ], [U("хочу выпить кофе с кем нибудь")])
check("переспрос: вторая попытка целиком", в["поток"] == 1 and в["целиком"] == 1, в)
check("переспрос: заявление первой не показано", "Помогу" not in показано, показано)

# 6. Недописанное предложение не уходит, пока не кончится.
печать = []
п = V2._Поток(печать.append, "ru", B)
for кусок in ("Вечер обещает быть тёп", "лым и тих", "им. Можно", " выйти"):
    п(кусок)
check("недописанное: ждёт точки", печать == ["Вечер обещает быть тёплым и тихим. "], печать)
п("\n###CARD\n{}")
check("маркер дописывает последнее", "".join(печать).strip().endswith("Можно выйти"), печать)

# 7. Чужой язык не печатается (ru-ход, английский ответ).
печать = []
п = V2._Поток(печать.append, "ru", B)
п("Sure, the evening is quiet and calm today. ")
п("And more text follows here. ")
check("язык: английский в ru-ходе не показан", печать == [], печать)

# 8. Падение потока до показа -> ответ целиком тем же ходом.
было_c, было_s = B.llm_complete, B.llm_stream
B.llm_stream = lambda *a, **k: (_ for _ in ()).throw(RuntimeError("обрыв"))
B.llm_complete = lambda *a, **k: "Понимаю, бывает. Отдохни как следует.\n" + _НЕТ
try:
    печать = []
    r = V2.ход([U("устал")], {}, {}, "ru", B, on_text=печать.append)
    check("обрыв до показа: ответ целиком", "Отдохни" in r[0] and печать == [], (r, печать))
finally:
    B.llm_complete, B.llm_stream = было_c, было_s

print("V2 STREAM RESULT: %d ok, %d failed" % (ok, fail))
sys.exit(1 if fail else 0)
