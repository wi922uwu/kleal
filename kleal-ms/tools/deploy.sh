#!/bin/bash
# ВЫКЛАДКА, НЕ ЛОМАЯ ЖИВОЙ КРУГ.
#
# ЗАЧЕМ. `tools/bench.sh` уже умеет ждать границы круга перед остановкой батареи — иначе замер
# рвёт круг и в панели это выглядит поломкой продукта. С выкладкой ровно то же самое, и 18.09.2026
# это стоило шести кругов подряд: перезапуск буди в 23:36 дал в круге 23:38 СЕТЬ=357, в 00:02 и
# 00:05 — СЕТЬ=374, в 00:44 и 00:45 — СЕТЬ=271. Круги без перезапуска в те же часы: СЕТЬ=0,
# собралось 472 и 468. То есть все «сбои сети» в истории были моими выкладками, а не продуктом.
#
# Поэтому: дождаться конца круга, остановить батарею, перезапустить службы, дождаться, пока они
# отвечают, и только потом вернуть батарею. Круг при этом не обрывается ни разу.
#
# Использование: tools/deploy.sh <служба> [<служба> ...]
#   tools/deploy.sh kleal@buddy
#   tools/deploy.sh kleal@buddy kleal@filtration
set -u
ROUNDS=/root/kleal-archive/battery-rounds.jsonl
[ $# -gt 0 ] || { echo "нужна хотя бы одна служба"; exit 2; }

RESUME=0
if systemctl is-active --quiet kleal-battery; then
    N0=$(wc -l < "$ROUNDS")
    echo "жду конца круга (сейчас кругов $N0, не больше 8 минут)"
    T=0
    while [ "$T" -lt 480 ]; do
        N=$(wc -l < "$ROUNDS")
        [ "$N" -gt "$N0" ] && break
        sleep 15; T=$((T+15))
    done
    echo "круг закрыт через $T с — останавливаю батарею"
    systemctl stop kleal-battery
    RESUME=1
    sleep 3
fi

RC=0
for U in "$@"; do
    echo "перезапускаю $U"
    systemctl restart "$U" || RC=1
done

# Ждём не «active», а настоящий ответ: служба помечается запущенной раньше, чем прогреет таксономию,
# и запрос в эту щель возвращает 502 — то самое, из-за чего круги и рвались.
for P in 7071 7072 7074 7075 7076 7080; do
    for i in $(seq 1 60); do
        curl -s -m 3 -o /dev/null "http://127.0.0.1:$P/health" && break
        sleep 1
    done
done
echo "службы отвечают"

[ "$RESUME" = 1 ] && { systemctl start kleal-battery; echo "батарея возвращена"; }
exit $RC
