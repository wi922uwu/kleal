# -*- coding: utf-8 -*-
"""Единичная проверка правил разговора — БЕЗ модели и без сети.

Здесь живут два правила, которые модель не соблюдает сама, сколько её ни проси в промпте:

  1. предложение «а хочешь обсудить это с кем-нибудь?» не лезет в каждый ответ;
  2. ход в игре — не просьба познакомить с кем-то.

Оба сняты с живых снимков 14 августа. Проверяются таблицей, потому что оба детерминированные:
это и есть причина, по которой они вынесены из промпта в код.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "services", "buddy"))
sys.path.insert(0, os.path.join(ROOT, "shared"))
import app as b

ok = fail = 0
def check(name, cond, detail=""):
    global ok, fail
    if cond:
        ok += 1
    else:
        fail += 1
        print("  FAIL %s   %s" % (name, str(detail)[:140]))


# ---- предложение вырезается, а ответ остаётся целым
CUT = [
    ("Фьючерсы — это контракты. Их используют для хеджирования. Хочешь обсудить это с кем-нибудь?",
     "хеджирования."),
    ("У бабушки давление — обратитесь к врачу и следите за диетой. Хочешь обсудить темы, "
     "связанные со здоровьем, с кем-нибудь?", "диетой."),
    ("Давай поиграем в ассоциации. Я начинаю со слова «облако». Хочешь обсудить игры с кем-нибудь?",
     "«облако»."),
]
for src, tail in CUT:
    got = b.strip_trailing_offer(src)
    check("вырезано: …%s" % tail, got.endswith(tail), got[-60:])

KEEP = "Падел — ракеточный спорт, попробуй в клубе рядом."
check("ответ без предложения не трогается", b.strip_trailing_offer(KEEP) == KEEP)
# Если предложение и БЫЛО ответом, отдать пустую строку нельзя.
short = "Хочешь обсудить это с кем-нибудь?"
check("одинокое предложение остаётся", b.strip_trailing_offer(short) == short)

# ---- когда предложение уместно
prev_offered = [{"role": "user", "content": "расскажи про кофе"},
                {"role": "assistant", "content": "Кофе бывает разный. Хочешь обсудить это с кем-нибудь?"}]
check("дважды подряд — нельзя", not b.offer_is_welcome(prev_offered, "x" * 300))
check("после вопроса про здоровье — нельзя",
      not b.offer_is_welcome([{"role": "user", "content": "у бабушки высокое давление"}], "x" * 300))
check("после вопроса про саму компанию — нельзя",
      not b.offer_is_welcome([{"role": "user", "content": "какая лицензия у вашей компании"}], "x" * 300))
check("посреди игры — нельзя",
      not b.offer_is_welcome([{"role": "user", "content": "давай поиграем в ассоциации"}], "x" * 300))
check("на коротком ответе — нельзя",
      not b.offer_is_welcome([{"role": "user", "content": "расскажи про падел"}], "Падел — это спорт."))
check("на длинном ответе про обычное — можно",
      b.offer_is_welcome([{"role": "user", "content": "расскажи про падел"}], "x" * 300))

# ---- ход в игре не просьба
GAME = [{"role": "user", "content": "давай поиграем в ассоциации"},
        {"role": "assistant", "content": "Давай! Я начинаю со слова «облако». Какое слово у тебя?"},
        {"role": "user", "content": "Непотребства"}]
check("одно слово в игре — ход", b._is_game_move("Непотребства", GAME))
check("просьба в игре — всё ещё просьба",
      not b._is_game_move("хочу найти компанию на падел", GAME))
check("одно слово ВНЕ игры ходом не считается",
      not b._is_game_move("Непотребства", [{"role": "assistant", "content": "Расскажи про себя."}]))

print("\nРЕЗУЛЬТАТ: %d ok, %d проблем" % (ok, fail))
sys.exit(1 if fail else 0)
