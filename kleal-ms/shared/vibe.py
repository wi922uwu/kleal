# -*- coding: utf-8 -*-
"""Настрой человека — одно слово, и единственное, что тест характера отдаёт подбору.

Признак `social_context` сверяет `vibe` двоих и знает пары-противоположности (introvert против
extrovert, chill против party): по замеру 15.09.2026 это САМЫЙ различающий признак выдачи. При
этом поле у человека не заполняется руками нигде: его выводит из ответов теста сам сервер.

Правило вывода жило в `services/matching/app.py`, и знал его только подбор — экран профиля не мог
показать человеку, каким его видят, а приложение не могло прислать настрой в поиск. Теперь правило
здесь, и его читают все: матчинг (дописывает карточкам), онбординг (отдаёт экрану «Твоя личность»
и принимает правку) и всё, что появится потом.
"""

# ЗАКРЫТЫЙ СЛОВАРЬ. Ранжировщик сравнивает настрои строкой, поэтому слово вне списка ничему не
# противоположно и ни с чем не совпадает — оно просто гасит признак. Первые шесть участвуют в
# матрице конфликтов (`VIBE_CLASH` обоих движков), остальные четыре сравниваются на равенство.
VIBES = ("chill", "party", "calm", "energetic", "introvert", "extrovert",
         "intellectual", "creative", "competitive", "social")

# Тест характера считает десять осей; на словарь подбора без натяжки ложатся две.
#   energy — «люди заряжают или забирают силы» — это и есть extrovert/introvert;
#   group  — «один на один или большая компания» — это chill/party.
# Решает energy: ось классическая и прямо названа в матрице конфликтов. Ответил «зависит» —
# решает размер компании, иначе половина ответивших осталась бы без настроя.
BY_ENERGY = {"energised": "extrovert", "drained": "introvert"}
BY_GROUP = {"crowd": "party", "small": "chill", "one": "chill"}


def from_persona(row):
    """Настрой из осей теста. Пусто — если тест не пройден или обе оси молчат."""
    p = (row or {}).get("persona")
    axes = p.get("axes") if isinstance(p, dict) else None
    if not isinstance(axes, dict):
        return ""
    v = BY_ENERGY.get(str(axes.get("energy") or "").strip().lower())
    if v:
        return v
    return BY_GROUP.get(str(axes.get("group") or "").strip().lower(), "")


def of(row):
    """Настрой строки: выбранный человеком, иначе выведенный из теста, иначе пусто.

    Выбранное руками СИЛЬНЕЕ теста и не проверяется по словарю: в строке может лежать слово из
    прежних времён, и молча подменять его выводом теста — значит спорить с человеком. Проверка
    стоит на записи (`clean`), там ей и место."""
    v = str((row or {}).get("vibe") or "").strip().lower()
    return v or from_persona(row)


def clean(value):
    """Значение, годное для записи: слово из словаря — или пусто (тогда поле не трогают)."""
    v = str(value or "").strip().lower()
    return v if v in VIBES else ""
