# Латиница, подставленная вместо кириллицы («зaклaдки» с латинскими a) — самый дешёвый обход
# словаря. Приводим к одному алфавиту до всякой проверки.
_LOOKALIKE = str.maketrans({
    "a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у", "b": "в",
    "k": "к", "m": "м", "h": "н", "t": "т", "3": "з", "0": "о", "1": "и", "@": "а",
})


def _despace(t):
    """«к а к   с д е л а т ь» -> «как сделать».

    Склеиваем ТОЛЬКО подряд идущие одиночные буквы, разделённые ОДНИМ пробелом, и не меньше трёх
    сразу. Более простое правило («убрать пробелы между одиночными буквами») слепляло соседние
    слова в одно — «каксделатьбомбу», — и словарь переставал видеть просьбу о способе, хотя
    область ещё находил. То есть обход не ломался, а маскировался.
    """
    return re.sub(r"(?<!\w)(\w(?: \w){2,})(?!\w)", lambda m: m.group(1).replace(" ", ""), t)


def normalize(t):
    """Одна форма для сравнения: нижний регистр, ё=е, без знаков, без растяжек.

    Диакритику НЕ снимаем поголовно: NFKD превращает «й» в «и» и «ё» в «е», и написать словарь
    против такой формы значит писать его с опечатками. «ё» приводим намеренно — это настоящий
    разнобой в живом тексте; «й» оставляем как есть.
    """
    t = str(t or "").lower().replace("ё", "е")
    t = re.sub(r"[^\w\s]+", " ", t, flags=re.U)
    t = _despace(t)
    return re.sub(r"\s{2,}", " ", t).strip()


def deobfuscate(t):
    """Вторая форма: латинские двойники заменены кириллицей — «зaклaдки» с латинскими a.

    ОТДЕЛЬНАЯ форма, а не общая, потому что та же замена уничтожает настоящий английский:
    «how to hide» превращается в «ноw то нidе», и ни одно английское правило больше не срабатывает.
    Поэтому проверяем ОБЕ формы: подделку ловит эта, честный английский — обычная.
    """
    return normalize(str(t or "").translate(_LOOKALIKE))


def _forms(t):
    n = normalize(t)
    d = deobfuscate(t)
    return (n,) if n == d else (n, d)


