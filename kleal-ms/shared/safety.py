def domains_in(text):
    """Какие опасные области упомянуты. Пусто — значит тема безопасная."""
    forms = _forms(text)
    return [k for k, rx in _DOMAIN_RE.items() if any(rx.search(f) for f in forms)]


def check(text):
    """(вердикт, область) для ОДНОЙ реплики.

    Вердикты:
      "block"  — просьба о способе в опасной области. Отказ, без обсуждения деталей.
      "care"   — область задета, но просьбы о способе нет: обычный разговор, но поток выключаем,
                 чтобы ответ можно было проверить целиком.
      "ok"     — ничего.

    Отдельно selfharm: там «care» не про безопасность продукта, а про человека — ответ должен
    быть тёплым и с телефоном помощи, а не отказом. Поэтому область возвращается всегда.
    """
    forms = _forms(text)
    doms = [k for k, rx in _DOMAIN_RE.items() if any(rx.search(f) for f in forms)]
    if not doms:
        return "ok", ""
    if "selfharm" in doms:
        return "selfharm", "selfharm"
    asked = any(_ASK.search(f) for f in forms)
    if asked:
        return "block", doms[0]
    # Рамка вымысла БЕЗ просьбы о способе — всё ещё разговор («пишу роман про 90-е»).
    # Но если рамка стоит рядом с опасной областью, ответ проверяем целиком.
    return "care", doms[0]


def check_conversation(messages, look_back=6):
    """То же, но по нескольким последним репликам человека.

    Просьбу дробят: «расскажи про закладки» … «а теперь именно метод». Вторая реплика сама по себе
    безобидна — область в ней не названа вовсе. Поэтому просьба о способе ищется в ПОСЛЕДНЕЙ
    реплике, а область — в нескольких предыдущих: это ровно тот обход, который сработал вживую.
    """
    users = [str(m.get("content") or "") for m in (messages or []) if m.get("role") == "user"]
    if not users:
        return "ok", ""
    last, tail = users[-1], users[-look_back:]
    v, d = check(last)
    if v in ("block", "selfharm"):
        return v, d
    doms = []
    for u in tail:
        doms += domains_in(u)
    if not doms:
        return v, d
    if "selfharm" in doms:
        return "selfharm", "selfharm"
    if any(_ASK.search(f) for f in _forms(last)):
        return "block", doms[0]
    return ("care", doms[0]) if v == "ok" else (v, d or doms[0])


def looks_operational(reply, domain):
    """Похож ли ГОТОВЫЙ ответ на инструкцию.

    Третий рубеж, и зовётся он ТОЛЬКО когда область уже установлена по вопросу (вердикт «care»):
    человек спросил про опасное, модель согласилась ответить. Поэтому саму область в ответе
    искать не нужно — ключевой промах снимка был именно тут: ответ говорил про «маршруты» и
    «коды», не называя наркотики ни разу, и проверка «есть ли область в тексте» его пропускала.

    Смотрим на ФОРМУ инструкции: нумерованные шаги или повелительное наклонение. Их наличие в
    ответе на опасный вопрос и есть признак того, что метод всё-таки выдан.
    """
    if not domain or domain == "selfharm":
        return False
    t = normalize(reply)
    steps = len(re.findall(r"(?m)^\s*(?:\d+[\.\)]|[-*•])\s+\S", str(reply or "")))
    imper = len(re.findall(r"\b(использ\w*|создай|сделай|возьми|выбери|разложи|спрячь|разработ\w*|"
                           r"use|create|choose|pick|hide|place|develop)\b", t))
    return steps >= 2 or imper >= 2
