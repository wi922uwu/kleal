# -*- coding: utf-8 -*-
"""География: расстояние между двумя точками. Одно место на всё дерево.

Формула лежала ТРИЖДЫ — в ранжировщике (services/matching/app.py), в выключенном движке
(services/matching/core_v2.py) и в сборщике признаков (matching_core/feature_builder/builder.py), —
и все три тела совпадали дословно: тот же радиус 6371.0088, та же формула, то же округление до
сотых. Отличалось только имя константы (R против Rk). Три копии одного числа — это три места, где
оно может разойтись, и ни одного способа заметить, что разошлось.

ЧЕГО ЗДЕСЬ НАМЕРЕННО НЕТ. Рядом с каждой копией лежал ещё и свой `_latlon` — и вот они РАЗНЫЕ.
Ранжировщик читает только `lat`/`lon` верхнего уровня и отбрасывает нулевую точку; сборщик
признаков и выключенный движок читают вложенный `geo` и четыре написания ключей. Свести их одним
движением нельзя: у ранжировщика от этого поменяется выдача. Два богатых читателя на боевых данных
сходятся точь-в-точь (833 строки, 630 с координатами у обоих, ноль расхождений) — их объединить
можно, и это сделано ниже. Простой читатель остаётся у себя, и над ним стоит об этом пометка.
"""
import math

#: Средний радиус Земли, км. Тот же, что был во всех трёх копиях.
EARTH_KM = 6371.0088


def haversine(a, b):
    """Расстояние между (широта, долгота) в километрах, округлённое до сотых."""
    la1, lo1, la2, lo2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = (math.sin((la2 - la1) / 2) ** 2
         + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2)
    return round(2 * EARTH_KM * math.asin(min(1.0, math.sqrt(h))), 2)


#: Все написания пары координат, которые встречались в данных. Порядок важен: грубая точка идёт
#: первой, потому что точную мы намеренно не храним у чужих профилей.
_PAIRS = (("coarseLat", "coarseLon"), ("coarseLat", "coarseLng"),
          ("coarse_lat", "coarse_lon"), ("lat", "lon"), ("lat", "lng"))


def latlon(obj):
    """Координаты профиля: сначала во вложенном `geo`, потом в самом объекте. None — если нет."""
    if not isinstance(obj, dict):
        return None
    inner = obj.get("geo") if isinstance(obj.get("geo"), dict) else None
    for src in (inner, obj):
        if not isinstance(src, dict):
            continue
        for la, lo in _PAIRS:
            if isinstance(src.get(la), (int, float)) and isinstance(src.get(lo), (int, float)):
                return (float(src[la]), float(src[lo]))
    return None
